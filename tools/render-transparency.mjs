// Renders /transparency/ — how well each city publishes its crime data.
//
// THE ONE DESIGN RULE HERE
// Every score on this page must be decomposable on screen. The argument the
// page makes is that a single number hiding incomparable inputs is worthless;
// publishing our own opaque 0-100 would be the same sin in a nicer typeface.
// So each row shows its four components as a stacked bar, cities where a
// component could not be measured say so rather than quietly scoring
// differently, and the weights are printed in the methodology.
//
// Data: tools/data/transparency-index.json, generated by the backend's
// scripts/transparency-index.mjs (every field measured by asking the feed).
//
// Usage: node tools/render-transparency.mjs

